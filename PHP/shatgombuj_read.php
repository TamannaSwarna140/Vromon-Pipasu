       কিন্তু বর্তমান অবস্থায় তা কল্পনা করাও কষ্টকর। বড় দালানকোঠায় ভরে উঠেছে মসজিদের চারপাশ। বর্তমানে প্রত্নতত্ত্ব অধিদপ্তর এর দেখাশোনার 
